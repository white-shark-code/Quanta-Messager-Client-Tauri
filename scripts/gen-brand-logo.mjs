/**
 * Regenerate `src/ui/components/BrandLogo.tsx` from the brand SVGs.
 *
 * The React logo components inline the artwork (so the mark scales
 * crisply and can inherit `currentColor`), which means the path data is
 * duplicated in the source. This script keeps that copy honest:
 *
 *   node scripts/gen-brand-logo.mjs
 *
 * Run it after re-exporting `brand/*.svg` from the VectorCraft source
 * (`brand/Quant-brand.vectorcraft`). The output is formatted with the
 * repo's Prettier config.
 */
/* global console */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

/** Pull `{id, d}` out of every `<path …>` in an exported SVG. */
function paths(svg) {
  const out = [];
  const re = /<path\b([^>]*)\/?>/g;
  let m;
  while ((m = re.exec(svg)) !== null) {
    const attrs = m[1];
    const d = /(?:^|\s)d="([^"]+)"/.exec(attrs);
    if (d === null) continue;
    const id = /id="([^"]+)"/.exec(attrs);
    out.push({ id: id === null ? null : id[1], d: d[1] });
  }
  return out;
}

const byId = (svg, id) => {
  const hit = paths(svg).find((p) => p.id === id);
  if (hit === undefined) throw new Error(`no <path id="${id}"> in the SVG`);
  return hit.d;
};

const markSvg = read("brand/quant-mark.svg");
const iconSvg = read("brand/quant-icon.svg");
const lockupSvg = read("brand/quant-lockup.svg");

const markPath = byId(markSvg, "disc");
const iconTile = byId(iconSvg, "tile");
const iconMark = byId(iconSvg, "disc");
const lockupMark = byId(lockupSvg, "disc");
const wordmark = paths(lockupSvg)
  .filter((p) => p.id === null)
  .map((p) => p.d);

if (wordmark.length === 0) throw new Error("no wordmark glyphs found in brand/quant-lockup.svg");

const q = (s) => JSON.stringify(s);

const file = `/**
 * Brand logo — inline SVG artwork so the mark stays crisp at any size and
 * can take its colour from the surrounding theme.
 *
 * Generated by \`scripts/gen-brand-logo.mjs\` from the brand SVGs
 * (\`brand/*.svg\`, redrawn in \`brand/Quant-brand.vectorcraft\`) — edit the
 * artwork and re-run the script instead of hand-editing the path data.
 *
 *   BrandMark    — the Q / keyhole mark alone (flat, currentColor-ready)
 *   BrandLockup  — mark + outlined wordmark "quant"
 *   BrandTile    — app icon: mark on the navy rounded tile
 */
import { useId, type CSSProperties } from "react";

const MARK_VIEWBOX = "122 166.7 780 690.6";
const MARK_RATIO = 780 / 690.6;

const LOCKUP_VIEWBOX = "188.5 122 1223 340";
const LOCKUP_RATIO = 1223 / 340;

const ICON_VIEWBOX = "0 0 1024 1024";

const MARK_PATH = ${q(markPath)};

const LOCKUP_MARK_PATH = ${q(lockupMark)};

const WORDMARK_PATHS: readonly string[] = [
${wordmark.map((d) => `  ${q(d)},`).join("\n")}
];

const ICON_TILE_PATH = ${q(iconTile)};

const ICON_MARK_PATH = ${q(iconMark)};

export interface BrandMarkProps {
  /** Rendered height in px; the width follows the artwork's ratio. */
  size?: number;
  /** Any CSS colour; defaults to the current text colour. */
  color?: string;
  /** Accessible name; pass an empty string to mark it decorative. */
  title?: string;
  className?: string;
  style?: CSSProperties;
}

/**
 * The mark alone — a speech-bubble Q with a keyhole counter.
 */
export function BrandMark({
  size = 40,
  color = "currentColor",
  title = "Quant",
  className,
  style,
}: BrandMarkProps): JSX.Element {
  return (
    <svg
      viewBox={MARK_VIEWBOX}
      width={size * MARK_RATIO}
      height={size}
      className={className}
      style={style}
      role={title === "" ? "presentation" : "img"}
      aria-label={title === "" ? undefined : title}
      aria-hidden={title === "" ? true : undefined}
      focusable="false"
    >
      <path d={MARK_PATH} fill={color} fillRule="nonzero" />
    </svg>
  );
}

export interface BrandLockupProps {
  /** Height of the artwork; the wordmark is set to match. */
  size?: number;
  /** Mark colour. */
  markColor?: string;
  /** Wordmark colour; defaults to the current text colour. */
  color?: string;
  title?: string;
  className?: string;
  style?: CSSProperties;
}

/**
 * Horizontal lockup: the mark followed by the outlined wordmark.
 */
export function BrandLockup({
  size = 32,
  markColor = "#1E88E5",
  color = "currentColor",
  title = "Quant",
  className,
  style,
}: BrandLockupProps): JSX.Element {
  return (
    <svg
      viewBox={LOCKUP_VIEWBOX}
      width={size * LOCKUP_RATIO}
      height={size}
      className={className}
      style={style}
      role={title === "" ? "presentation" : "img"}
      aria-label={title === "" ? undefined : title}
      aria-hidden={title === "" ? true : undefined}
      focusable="false"
    >
      <path d={LOCKUP_MARK_PATH} fill={markColor} fillRule="nonzero" />
      {WORDMARK_PATHS.map((d) => (
        <path key={d.slice(0, 32)} d={d} fill={color} />
      ))}
    </svg>
  );
}

export interface BrandTileProps {
  /** Rendered size in px (the artwork is square). */
  size?: number;
  title?: string;
  className?: string;
  style?: CSSProperties;
}

/**
 * The app icon: gradient mark on the navy rounded tile.
 */
export function BrandTile({
  size = 96,
  title = "Quant",
  className,
  style,
}: BrandTileProps): JSX.Element {
  const uid = useId().replace(/[^a-zA-Z0-9_-]/g, "");
  const tileId = \`quant-tile-\${uid}\`;
  const markId = \`quant-mark-\${uid}\`;
  return (
    <svg
      viewBox={ICON_VIEWBOX}
      width={size}
      height={size}
      className={className}
      style={style}
      role={title === "" ? "presentation" : "img"}
      aria-label={title === "" ? undefined : title}
      aria-hidden={title === "" ? true : undefined}
      focusable="false"
    >
      <defs>
        <linearGradient
          id={tileId}
          x1="120"
          y1="40"
          x2="950"
          y2="1024"
          gradientUnits="userSpaceOnUse"
        >
          <stop offset="0" stopColor="#1B3F6E" />
          <stop offset="0.48" stopColor="#0E2241" />
          <stop offset="1" stopColor="#070F1C" />
        </linearGradient>
        <linearGradient
          id={markId}
          x1="210"
          y1="215"
          x2="830"
          y2="800"
          gradientUnits="userSpaceOnUse"
        >
          <stop offset="0" stopColor="#B7F1FF" />
          <stop offset="0.42" stopColor="#5CC6FF" />
          <stop offset="1" stopColor="#2E9BFF" />
        </linearGradient>
      </defs>
      <path d={ICON_TILE_PATH} fill={\`url(#\${tileId})\`} />
      <path d={ICON_MARK_PATH} fill={\`url(#\${markId})\`} fillRule="nonzero" />
    </svg>
  );
}
`;

const out = join(root, "src/ui/components/BrandLogo.tsx");
writeFileSync(out, file);
execFileSync("npx", ["prettier", "--write", out], { cwd: root, stdio: "inherit" });
console.log(`BrandLogo.tsx: ${wordmark.length} wordmark glyphs, ${file.length} bytes`);
